//! Theme renderers for terminals, editors and desktop apps beyond the core
//! set: kitty, foot, Alacritty, WezTerm, Helix, Neovim, Firefox (pywal
//! colours + userChrome variables), Vesktop / Vencord and KDE colour
//! schemes. Each is a pure function of the palette; [`super::sync`]
//! writes them to Mandara-owned files only.

use crate::color::Color;
use crate::palette::MandaraPalette;

use super::ansi;

/// Alpha of selection / highlight backgrounds layered over surfaces.
const SELECTION_ALPHA: f32 = 0.35;
/// Alpha of the cursor-line / subtle highlight background.
const CURSORLINE_MIX: f32 = 0.5;

/// `#rrggbb` (opaque) — every app below expects plain six-digit hex.
fn hex(c: Color) -> String {
    format!("#{}", c.to_hex_rgb_bare())
}

/// `r,g,b` decimal triple (KDE colour schemes).
fn rgb(c: Color) -> String {
    let [r, g, b, _] = c.to_rgba8();
    format!("{r},{g},{b}")
}

/// A selection colour flattened over the background (apps without alpha).
fn selection(p: &MandaraPalette) -> Color {
    p.primary.with_alpha(SELECTION_ALPHA).over(p.surface_base)
}

fn header(p: &MandaraPalette, comment: &str) -> String {
    format!("{comment} Generated by Mandara Shell from \"{}\" — regenerated on every theme change.\n", p.name)
}

/// kitty colour theme (`include` it or pick it with `kitten themes`).
pub fn kitty(p: &MandaraPalette) -> String {
    let mut s = header(p, "#");
    let pairs = [
        ("foreground", p.on_surface),
        ("background", p.surface_base),
        ("selection_foreground", p.on_surface),
        ("selection_background", selection(p)),
        ("cursor", p.primary),
        ("cursor_text_color", p.on_primary),
        ("url_color", p.tertiary),
        ("active_border_color", p.primary),
        ("inactive_border_color", p.outline),
        ("active_tab_foreground", p.on_primary),
        ("active_tab_background", p.primary),
        ("inactive_tab_foreground", p.on_surface_variant),
        ("inactive_tab_background", p.surface_container),
        ("tab_bar_background", p.surface_dim),
    ];
    for (k, c) in pairs {
        s.push_str(&format!("{k} {}\n", hex(c)));
    }
    for (i, c) in ansi(p).iter().enumerate() {
        s.push_str(&format!("color{i} {}\n", hex(*c)));
    }
    s
}

/// foot `[colors]` section (`include=` it from foot.ini).
pub fn foot(p: &MandaraPalette) -> String {
    let bare = |c: Color| c.to_hex_rgb_bare();
    let a = ansi(p);
    let mut s = header(p, "#");
    s.push_str("[colors]\n");
    s.push_str(&format!("foreground={}\nbackground={}\n", bare(p.on_surface), bare(p.surface_base)));
    s.push_str(&format!("selection-foreground={}\nselection-background={}\n", bare(p.on_surface), bare(selection(p))));
    s.push_str(&format!("urls={}\n", bare(p.tertiary)));
    for (i, c) in a.iter().take(8).enumerate() {
        s.push_str(&format!("regular{i}={}\n", bare(*c)));
    }
    for (i, c) in a.iter().skip(8).enumerate() {
        s.push_str(&format!("bright{i}={}\n", bare(*c)));
    }
    s.push_str(&format!("[cursor]\ncolor={} {}\n", bare(p.on_primary), bare(p.primary)));
    s
}

const ANSI_NAMES: [&str; 8] = ["black", "red", "green", "yellow", "blue", "magenta", "cyan", "white"];

/// Alacritty TOML colours (`general.import` it).
pub fn alacritty(p: &MandaraPalette) -> String {
    let a = ansi(p);
    let mut s = header(p, "#");
    s.push_str(&format!("[colors.primary]\nforeground = \"{}\"\nbackground = \"{}\"\n\n", hex(p.on_surface), hex(p.surface_base)));
    s.push_str(&format!("[colors.cursor]\ntext = \"{}\"\ncursor = \"{}\"\n\n", hex(p.on_primary), hex(p.primary)));
    s.push_str(&format!("[colors.selection]\ntext = \"{}\"\nbackground = \"{}\"\n\n", hex(p.on_surface), hex(selection(p))));
    for (section, offset) in [("normal", 0), ("bright", ANSI_NAMES.len())] {
        s.push_str(&format!("[colors.{section}]\n"));
        for (i, name) in ANSI_NAMES.iter().enumerate() {
            s.push_str(&format!("{name} = \"{}\"\n", hex(a[offset + i])));
        }
        s.push('\n');
    }
    s
}

/// WezTerm colour scheme (`~/.config/wezterm/colors/`, `color_scheme = "Mandara"`).
pub fn wezterm(p: &MandaraPalette) -> String {
    let a = ansi(p);
    let list = |cs: &[Color]| cs.iter().map(|c| format!("\"{}\"", hex(*c))).collect::<Vec<_>>().join(", ");
    let mut s = header(p, "#");
    s.push_str("[colors]\n");
    s.push_str(&format!("foreground = \"{}\"\nbackground = \"{}\"\n", hex(p.on_surface), hex(p.surface_base)));
    s.push_str(&format!("cursor_bg = \"{}\"\ncursor_fg = \"{}\"\ncursor_border = \"{}\"\n", hex(p.primary), hex(p.on_primary), hex(p.primary)));
    s.push_str(&format!("selection_bg = \"{}\"\nselection_fg = \"{}\"\n", hex(selection(p)), hex(p.on_surface)));
    s.push_str(&format!("ansi = [{}]\nbrights = [{}]\n", list(&a[..8]), list(&a[8..])));
    s.push_str("\n[metadata]\nname = \"Mandara\"\n");
    s
}

/// Helix theme (`theme = "mandara"` in config.toml).
pub fn helix(p: &MandaraPalette) -> String {
    let a = ansi(p);
    let mut s = header(p, "#");
    let scopes: [(&str, &str); 34] = [
        ("ui.background", "{ bg = \"base\" }"),
        ("ui.text", "\"text\""),
        ("ui.text.focus", "{ fg = \"primary\", modifiers = [\"bold\"] }"),
        ("ui.cursor", "{ fg = \"on_primary\", bg = \"primary\" }"),
        ("ui.cursor.primary", "{ fg = \"on_primary\", bg = \"primary\" }"),
        ("ui.cursor.match", "{ bg = \"selection\", modifiers = [\"bold\"] }"),
        ("ui.cursorline.primary", "{ bg = \"cursorline\" }"),
        ("ui.selection", "{ bg = \"selection\" }"),
        ("ui.linenr", "\"outline\""),
        ("ui.linenr.selected", "{ fg = \"primary\", modifiers = [\"bold\"] }"),
        ("ui.statusline", "{ fg = \"text\", bg = \"container\" }"),
        ("ui.statusline.inactive", "{ fg = \"subtle\", bg = \"low\" }"),
        ("ui.statusline.normal", "{ fg = \"on_primary\", bg = \"primary\" }"),
        ("ui.statusline.insert", "{ fg = \"on_primary\", bg = \"green\" }"),
        ("ui.statusline.select", "{ fg = \"on_primary\", bg = \"tertiary\" }"),
        ("ui.popup", "{ fg = \"text\", bg = \"high\" }"),
        ("ui.window", "\"outline\""),
        ("ui.help", "{ fg = \"text\", bg = \"high\" }"),
        ("ui.menu", "{ fg = \"text\", bg = \"high\" }"),
        ("ui.menu.selected", "{ fg = \"on_primary\", bg = \"primary\" }"),
        ("ui.virtual.whitespace", "\"outline\""),
        ("ui.virtual.ruler", "{ bg = \"low\" }"),
        ("comment", "{ fg = \"subtle\", modifiers = [\"italic\"] }"),
        ("keyword", "\"magenta\""),
        ("function", "\"blue\""),
        ("type", "\"yellow\""),
        ("string", "\"green\""),
        ("constant", "\"cyan\""),
        ("variable", "\"text\""),
        ("operator", "\"subtle\""),
        ("error", "\"red\""),
        ("warning", "\"yellow\""),
        ("info", "\"blue\""),
        ("hint", "\"cyan\""),
    ];
    for (scope, style) in scopes {
        s.push_str(&format!("\"{scope}\" = {style}\n"));
    }
    s.push_str("\n[palette]\n");
    let named = [
        ("base", p.surface_base),
        ("low", p.surface_container_low),
        ("container", p.surface_container),
        ("high", p.surface_container_high),
        ("text", p.on_surface),
        ("subtle", p.on_surface_variant),
        ("outline", p.outline),
        ("primary", p.primary),
        ("on_primary", p.on_primary),
        ("tertiary", p.tertiary),
        ("selection", selection(p)),
        ("cursorline", p.surface_container_low.mix(p.surface_base, CURSORLINE_MIX)),
        ("red", a[1]),
        ("green", a[2]),
        ("yellow", a[3]),
        ("blue", a[4]),
        ("magenta", a[5]),
        ("cyan", a[6]),
    ];
    for (k, c) in named {
        s.push_str(&format!("{k} = \"{}\"\n", hex(c)));
    }
    s
}

/// Neovim colourscheme in Lua (`:colorscheme mandara`).
pub fn neovim(p: &MandaraPalette) -> String {
    let a = ansi(p);
    let mut s = header(p, "--");
    s.push_str("vim.cmd('highlight clear')\nvim.g.colors_name = 'mandara'\n");
    s.push_str(&format!("vim.o.background = '{}'\n", if p.is_dark { "dark" } else { "light" }));
    s.push_str("local hl = function(group, spec) vim.api.nvim_set_hl(0, group, spec) end\n");
    let groups: [(&str, String); 26] = [
        ("Normal", format!("{{ fg = '{}', bg = '{}' }}", hex(p.on_surface), hex(p.surface_base))),
        ("NormalFloat", format!("{{ fg = '{}', bg = '{}' }}", hex(p.on_surface), hex(p.surface_container_high))),
        ("FloatBorder", format!("{{ fg = '{}', bg = '{}' }}", hex(p.outline), hex(p.surface_container_high))),
        ("Cursor", format!("{{ fg = '{}', bg = '{}' }}", hex(p.on_primary), hex(p.primary))),
        ("CursorLine", format!("{{ bg = '{}' }}", hex(p.surface_container_low))),
        ("CursorLineNr", format!("{{ fg = '{}', bold = true }}", hex(p.primary))),
        ("LineNr", format!("{{ fg = '{}' }}", hex(p.outline))),
        ("Visual", format!("{{ bg = '{}' }}", hex(selection(p)))),
        ("Search", format!("{{ fg = '{}', bg = '{}' }}", hex(p.on_primary), hex(p.primary))),
        ("Pmenu", format!("{{ fg = '{}', bg = '{}' }}", hex(p.on_surface), hex(p.surface_container_high))),
        ("PmenuSel", format!("{{ fg = '{}', bg = '{}' }}", hex(p.on_primary), hex(p.primary))),
        ("StatusLine", format!("{{ fg = '{}', bg = '{}' }}", hex(p.on_surface), hex(p.surface_container))),
        ("StatusLineNC", format!("{{ fg = '{}', bg = '{}' }}", hex(p.on_surface_variant), hex(p.surface_container_low))),
        ("WinSeparator", format!("{{ fg = '{}' }}", hex(p.outline))),
        ("Comment", format!("{{ fg = '{}', italic = true }}", hex(p.on_surface_variant))),
        ("Constant", format!("{{ fg = '{}' }}", hex(a[6]))),
        ("String", format!("{{ fg = '{}' }}", hex(a[2]))),
        ("Identifier", format!("{{ fg = '{}' }}", hex(p.on_surface))),
        ("Function", format!("{{ fg = '{}' }}", hex(a[4]))),
        ("Statement", format!("{{ fg = '{}' }}", hex(a[5]))),
        ("Type", format!("{{ fg = '{}' }}", hex(a[3]))),
        ("Special", format!("{{ fg = '{}' }}", hex(p.tertiary))),
        ("DiagnosticError", format!("{{ fg = '{}' }}", hex(p.urgent_coral))),
        ("DiagnosticWarn", format!("{{ fg = '{}' }}", hex(p.warning_amber))),
        ("DiagnosticInfo", format!("{{ fg = '{}' }}", hex(a[4]))),
        ("DiagnosticHint", format!("{{ fg = '{}' }}", hex(a[6]))),
    ];
    for (g, spec) in groups {
        s.push_str(&format!("hl('{g}', {spec})\n"));
    }
    for (i, c) in a.iter().enumerate() {
        s.push_str(&format!("vim.g.terminal_color_{i} = '{}'\n", hex(*c)));
    }
    s
}

/// Pywal-format `colors.json` (what Pywalfox reads for Firefox / Zen).
pub fn pywal_json(p: &MandaraPalette, wallpaper: &str) -> String {
    let a = ansi(p);
    let colors: Vec<String> = a.iter().enumerate().map(|(i, c)| format!("    \"color{i}\": \"{}\"", hex(*c))).collect();
    let wallpaper = wallpaper.replace('\\', "\\\\").replace('"', "\\\"");
    format!(
        "{{\n  \"wallpaper\": \"{wallpaper}\",\n  \"alpha\": \"100\",\n  \"special\": {{\n    \"background\": \"{}\",\n    \"foreground\": \"{}\",\n    \"cursor\": \"{}\"\n  }},\n  \"colors\": {{\n{}\n  }}\n}}\n",
        hex(p.surface_base),
        hex(p.on_surface),
        hex(p.primary),
        colors.join(",\n")
    )
}

/// CSS custom properties for Firefox's `userChrome.css` (`@import` it).
pub fn firefox_userchrome(p: &MandaraPalette) -> String {
    let vars = [
        ("--toolbar-bgcolor", p.surface_container),
        ("--toolbar-color", p.on_surface),
        ("--lwt-accent-color", p.surface_dim),
        ("--lwt-text-color", p.on_surface),
        ("--tab-selected-bgcolor", p.surface_container_high),
        ("--tab-selected-textcolor", p.on_surface),
        ("--toolbar-field-background-color", p.surface_container_low),
        ("--toolbar-field-color", p.on_surface),
        ("--toolbar-field-focus-border-color", p.primary),
        ("--arrowpanel-background", p.surface_container_high),
        ("--arrowpanel-color", p.on_surface),
        ("--focus-outline-color", p.primary),
        ("--sidebar-background-color", p.surface_container_low),
        ("--sidebar-text-color", p.on_surface),
    ];
    let mut s = format!("/* Generated by Mandara Shell from \"{}\". */\n:root {{\n", p.name);
    for (k, c) in vars {
        s.push_str(&format!("  {k}: {} !important;\n", hex(c)));
    }
    s.push_str("}\n");
    s
}

/// Vesktop / Vencord theme (`~/.config/vesktop/themes/`).
pub fn vesktop(p: &MandaraPalette) -> String {
    let vars = [
        ("--background-primary", p.surface_base),
        ("--background-secondary", p.surface_container_low),
        ("--background-secondary-alt", p.surface_container),
        ("--background-tertiary", p.surface_dim),
        ("--background-floating", p.surface_container_high),
        ("--background-modifier-hover", p.surface_container),
        ("--background-modifier-selected", p.surface_container_high),
        ("--channeltextarea-background", p.surface_container),
        ("--text-normal", p.on_surface),
        ("--text-muted", p.on_surface_variant),
        ("--header-primary", p.on_surface),
        ("--header-secondary", p.on_surface_variant),
        ("--interactive-normal", p.on_surface_variant),
        ("--interactive-hover", p.on_surface),
        ("--interactive-active", p.primary),
        ("--brand-experiment", p.primary),
        ("--text-link", p.tertiary),
        ("--status-danger", p.urgent_coral),
        ("--status-positive", p.success_emerald),
        ("--status-warning", p.warning_amber),
    ];
    let mut s = format!(
        "/**\n * @name Mandara\n * @author Mandara Shell\n * @description Follows the Mandara Shell palette (\"{}\"). Regenerated on every theme change.\n */\n:root, .theme-dark, .theme-light {{\n",
        p.name
    );
    for (k, c) in vars {
        s.push_str(&format!("  {k}: {} !important;\n", hex(c)));
    }
    s.push_str("}\n");
    s
}

/// KDE / Plasma colour scheme (`~/.local/share/color-schemes/Mandara.colors`).
pub fn kde(p: &MandaraPalette) -> String {
    // (section, background normal, background alternate, foreground)
    let sections = [
        ("Colors:Window", p.surface_base, p.surface_container_low, p.on_surface),
        ("Colors:View", p.surface_dim, p.surface_container_low, p.on_surface),
        ("Colors:Button", p.surface_container_high, p.surface_container, p.on_surface),
        ("Colors:Selection", p.primary, p.primary_container, p.on_primary),
        ("Colors:Tooltip", p.surface_container_high, p.surface_container, p.on_surface),
        ("Colors:Complementary", p.surface_dim, p.surface_container_low, p.on_surface),
        ("Colors:Header", p.surface_container, p.surface_container_low, p.on_surface),
    ];
    let mut s = header(p, "#");
    for (name, bg, alt, fg) in sections {
        s.push_str(&format!(
            "[{name}]\nBackgroundNormal={}\nBackgroundAlternate={}\nForegroundNormal={}\nForegroundInactive={}\nForegroundActive={}\nForegroundLink={}\nForegroundVisited={}\nForegroundNegative={}\nForegroundNeutral={}\nForegroundPositive={}\nDecorationFocus={}\nDecorationHover={}\n\n",
            rgb(bg),
            rgb(alt),
            rgb(fg),
            rgb(p.on_surface_variant),
            rgb(p.primary),
            rgb(p.tertiary),
            rgb(p.secondary),
            rgb(p.urgent_coral),
            rgb(p.warning_amber),
            rgb(p.success_emerald),
            rgb(p.primary),
            rgb(p.primary),
        ));
    }
    s.push_str(&format!(
        "[General]\nColorScheme=Mandara\nName=Mandara\nshadeSortColumn=true\n\n[KDE]\ncontrast=4\n\n[WM]\nactiveBackground={}\nactiveForeground={}\ninactiveBackground={}\ninactiveForeground={}\n",
        rgb(p.surface_container),
        rgb(p.on_surface),
        rgb(p.surface_base),
        rgb(p.on_surface_variant)
    ));
    s
}

#[cfg(test)]
mod tests {
    use super::*;

    fn palettes() -> [MandaraPalette; 2] {
        [crate::engine::default_palette(true), crate::engine::default_palette(false)]
    }

    #[test]
    fn terminals_carry_all_sixteen_colors() {
        for p in palettes() {
            let a = ansi(&p);
            let k = kitty(&p);
            assert!(k.contains(&format!("color15 {}", hex(a[15]))) && k.contains(&format!("background {}", hex(p.surface_base))));
            let f = foot(&p);
            assert_eq!(f.lines().filter(|l| l.starts_with("regular") || l.starts_with("bright")).count(), 16);
            assert!(f.contains("[colors]") && f.contains("[cursor]"));
            let al: toml::Table = toml::from_str(&alacritty(&p)).expect("alacritty TOML parses");
            assert_eq!(al["colors"]["bright"]["white"].as_str(), Some(hex(a[15]).as_str()));
            let wz: toml::Table = toml::from_str(&wezterm(&p)).expect("wezterm TOML parses");
            assert_eq!(wz["colors"]["ansi"].as_array().unwrap().len(), 8);
            assert_eq!(wz["colors"]["brights"].as_array().unwrap().len(), 8);
        }
    }

    #[test]
    fn helix_theme_resolves_every_palette_name() {
        let p = crate::engine::default_palette(true);
        let theme: toml::Table = toml::from_str(&helix(&p)).expect("helix TOML parses");
        let palette = theme["palette"].as_table().unwrap();
        // Every colour referenced by a scope is defined in [palette].
        for (scope, style) in &theme {
            if scope == "palette" {
                continue;
            }
            let names: Vec<String> = match style {
                toml::Value::String(s) => vec![s.clone()],
                toml::Value::Table(t) => ["fg", "bg"].iter().filter_map(|k| t.get(*k).and_then(|v| v.as_str()).map(str::to_string)).collect(),
                _ => panic!("unexpected style for {scope}"),
            };
            for n in names {
                assert!(palette.contains_key(&n), "{scope} uses undefined colour {n}");
            }
        }
    }

    #[test]
    fn neovim_and_css_themes() {
        let p = crate::engine::default_palette(false);
        let nv = neovim(&p);
        assert!(nv.contains("vim.o.background = 'light'") && nv.contains("vim.g.terminal_color_15"));
        assert_eq!(nv.matches("hl('").count(), 26);
        let ff = firefox_userchrome(&p);
        assert!(ff.contains(&format!("--toolbar-field-focus-border-color: {} !important", hex(p.primary))));
        let vk = vesktop(&p);
        assert!(vk.starts_with("/**") && vk.contains("@name Mandara") && vk.contains("--brand-experiment"));
        assert_eq!(vk.matches('{').count(), vk.matches('}').count());
    }

    #[test]
    fn pywal_json_is_valid() {
        let p = crate::engine::default_palette(true);
        let v: serde_json::Value = serde_json::from_str(&pywal_json(&p, "/home/u/Pictures/a \"b\".jpg")).expect("valid JSON");
        assert_eq!(v["colors"].as_object().unwrap().len(), 16);
        assert_eq!(v["special"]["background"], hex(p.surface_base));
        assert_eq!(v["wallpaper"], "/home/u/Pictures/a \"b\".jpg");
    }

    #[test]
    fn kde_scheme_has_every_section() {
        let p = crate::engine::default_palette(true);
        let k = kde(&p);
        for section in ["[Colors:Window]", "[Colors:View]", "[Colors:Button]", "[Colors:Selection]", "[General]", "[WM]"] {
            assert!(k.contains(section), "{section}");
        }
        let [r, g, b, _] = p.primary.to_rgba8();
        assert!(k.contains(&format!("BackgroundNormal={r},{g},{b}")), "selection background is the accent");
    }
}
