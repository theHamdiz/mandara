/// A qt6ct / qt5ct color scheme (21 roles per group).
pub fn qt(p: &MandaraPalette) -> String {
    let h = |c: Color| format!("#ff{}", c.to_hex_rgb_bare());
    // WindowText, Button, Light, Midlight, Dark, Mid, Text, BrightText,
    // ButtonText, Base, Window, Shadow, Highlight, HighlightedText, Link,
    // LinkVisited, AlternateBase, NoRole, ToolTipBase, ToolTipText,
    // PlaceholderText.
    let roles = |fg: Color| {
        [
            fg,
            p.surface_container_high,
            p.surface_container_high.lighten(0.08),
            p.surface_container,
            p.surface_dim,
            p.surface_container_low,
            fg,
            p.on_surface,
            fg,
            p.surface_dim,
            p.surface_base,
            Color::hex("#000000"),
            p.primary,
            p.on_primary,
            p.primary,
            p.tertiary,
            p.surface_container_low,
            p.surface_base,
            p.surface_container_high,
            p.on_surface,
            p.on_surface_variant,
        ]
        .into_iter()
        .map(h)
        .collect::<Vec<_>>()
        .join(", ")
    };
    format!(
        "# Generated by Mandara Shell from \"{}\".\n[ColorScheme]\nactive_colors={}\ninactive_colors={}\ndisabled_colors={}\n",
        p.name,
        roles(p.on_surface),
        roles(p.on_surface),
        roles(p.on_surface_variant.with_alpha(0.6)),
    )
}

