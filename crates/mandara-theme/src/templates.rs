    /// `text` mentions `c` as `rrggbb` (any case, with or without `#`) or
    /// as `r,g,b` (KDE).
    fn mentions(text: &str, c: Color) -> bool {
        let [r, g, b, _] = c.to_rgba8();
        let lower = text.to_lowercase();
        lower.contains(&c.to_hex_rgb_bare()) || text.contains(&format!("{r},{g},{b}"))
    }

