/// Kvantum's theme name (and folder / file stem).
pub const KVANTUM_THEME: &str = "Mandara";

/// SVG elements the Kvantum theme draws: `(element, corner radius)`.
const KV_ELEMENTS: &[(&str, f32)] = &[("button", 6.0), ("lineedit", 6.0), ("tab", 6.0), ("itemview", 4.0), ("menuitem", 4.0), ("menu", 8.0), ("tooltip", 6.0), ("progress", 4.0), ("groove", 3.0)];
const KV_STATES: &[&str] = &["normal", "focused", "pressed", "toggled", "disabled"];

/// `(interior, frame)` colors of a Kvantum element in a state.
fn kv_colors(p: &MandaraPalette, element: &str, state: &str) -> (Color, Color) {
    let rim = p.outline.with_alpha(0.35);
    match (element, state) {
        (_, "disabled") => (p.surface_container_low, p.outline.with_alpha(0.15)),
        ("progress", _) => (p.primary, p.primary),
        ("groove", _) => (p.surface_container_high, p.surface_container_high),
        ("menu", _) => (p.surface_container_high, rim),
        ("tooltip", _) => (p.surface_container_high, rim),
        ("itemview" | "menuitem", "normal") => (p.surface_base.with_alpha(0.0), p.surface_base.with_alpha(0.0)),
        ("itemview" | "menuitem", "focused") => (p.on_surface.with_alpha(0.08), p.on_surface.with_alpha(0.0)),
        ("itemview" | "menuitem", _) => (p.primary_container, p.primary_container),
        ("lineedit", "focused") => (p.surface_dim, p.primary),
        ("lineedit", _) => (p.surface_dim, rim),
        ("tab", "normal") => (p.surface_container, p.surface_container),
        ("tab", "focused") => (p.surface_container_high, p.surface_container_high),
        ("tab", _) => (p.surface_base, p.primary.with_alpha(0.6)),
        (_, "normal") => (p.surface_container_high, rim),
        (_, "focused") => (p.surface_container_high.lighten(0.04), p.primary.with_alpha(0.7)),
        (_, "pressed") => (p.primary_container, p.primary.with_alpha(0.6)),
        _ => (p.primary_container, p.primary),
    }
}

fn svg_fill(c: Color) -> String {
    format!("fill=\"#{}\" fill-opacity=\"{:.3}\"", c.to_hex_rgb_bare(), c.alpha())
}

/// The Kvantum SVG: for every element and state an interior (`button-normal`)
/// and its eight frame pieces (`button-normal-top`, `…-topleft`, …), each
/// on its own 24 px cell so Kvantum can slice them.
pub fn kvantum_svg(p: &MandaraPalette) -> String {
    const CELL: f32 = 24.0;
    const F: f32 = 3.0;
    let mut body = String::new();
    let mut y = 0.0;
    for (element, radius) in KV_ELEMENTS {
        for state in KV_STATES {
            let (interior, frame) = kv_colors(p, element, state);
            let id = format!("{element}-{state}");
            body.push_str(&format!("  <rect id=\"{id}\" x=\"0\" y=\"{y}\" width=\"{CELL}\" height=\"{CELL}\" {} />\n", svg_fill(interior)));
            // Frame slices: corners are quarter-rounded, edges are bands.
            let x0 = CELL * 2.0;
            let r = radius.min(F);
            let pieces = [
                ("topleft", 0.0, 0.0, F, F),
                ("top", F, 0.0, CELL, F),
                ("topright", F + CELL, 0.0, F, F),
                ("left", 0.0, F, F, CELL),
                ("right", F + CELL, F, F, CELL),
                ("bottomleft", 0.0, F + CELL, F, F),
                ("bottom", F, F + CELL, CELL, F),
                ("bottomright", F + CELL, F + CELL, F, F),
            ];
            for (side, dx, dy, w, h) in pieces {
                let rx = if side.len() > 6 { r } else { 0.0 };
                body.push_str(&format!(
                    "  <rect id=\"{id}-{side}\" x=\"{}\" y=\"{}\" width=\"{w}\" height=\"{h}\" rx=\"{rx}\" {} />\n",
                    x0 + dx,
                    y + dy,
                    svg_fill(frame)
                ));
            }
            y += CELL + 2.0 * F + 4.0;
        }
    }
    format!(
        "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n<!-- Generated by Mandara Shell from \"{}\". -->\n<svg xmlns=\"http://www.w3.org/2000/svg\" width=\"{}\" height=\"{y}\">\n{body}</svg>\n",
        xml_escape(&p.name),
        CELL * 4.0
    )
}

fn xml_escape(s: &str) -> String {
    s.replace('&', "&amp;").replace('<', "&lt;").replace('>', "&gt;").replace('"', "&quot;").replace("--", "- -")
}

