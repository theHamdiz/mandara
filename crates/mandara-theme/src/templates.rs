/// The 16 ANSI colors for terminals, harmonized toward the accent and
/// tuned for the palette's lightness.
pub fn ansi(p: &MandaraPalette) -> [Color; 16] {
    // OKLCH hues of red, green, yellow, blue, magenta, cyan.
    const HUES: [f32; 6] = [25.0, 145.0, 90.0, 255.0, 330.0, 200.0];
    let (l, lb, c) = if p.is_dark { (0.70, 0.80, 0.13) } else { (0.52, 0.44, 0.14) };
    let tone = |h: f32, light: f32| Color::oklch(light, c, h).harmonize_toward(p.primary).gamut_mapped();
    let mut out = [Color::hex("#000000"); 16];
    out[0] = p.surface_container_high;
    out[7] = p.on_surface_variant;
    out[8] = p.outline;
    out[15] = p.on_surface;
    for (i, h) in HUES.iter().enumerate() {
        out[i + 1] = tone(*h, l);
        out[i + 9] = tone(*h, lb);
    }
    out
}

pub fn ghostty(p: &MandaraPalette) -> String {
    let mut s = format!(
        "# Generated by Mandara Shell from \"{}\" — regenerated on every theme change.\n\
         background = {}\nforeground = {}\ncursor-color = {}\ncursor-text = {}\n\
         selection-background = {}\nselection-foreground = {}\n",
        p.name,
        p.surface_base.to_hex_rgb_bare(),
        p.on_surface.to_hex_rgb_bare(),
        p.primary.to_hex_rgb_bare(),
        p.on_primary.to_hex_rgb_bare(),
        p.primary_container.to_hex_rgb_bare(),
        p.on_surface.to_hex_rgb_bare(),
    );
    for (i, c) in ansi(p).iter().enumerate() {
        s.push_str(&format!("palette = {i}=#{}\n", c.to_hex_rgb_bare()));
    }
    s
}

